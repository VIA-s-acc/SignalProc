"""Generate the 256-entry viridis table for the TUI heat maps."""

import argparse
from pathlib import Path

import matplotlib
from matplotlib import colormaps


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    cmap = colormaps["viridis"].resampled(256)
    rows = []
    for i in range(256):
        r, g, b, _ = cmap(i)
        rows.append(f"{{{round(r * 255)}, {round(g * 255)}, {round(b * 255)}}},")
    header = f"// Generated by tools/gen_luts.py from matplotlib {matplotlib.__version__}; regenerate, do not edit."
    args.out.write_text(header + "\n" + "\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
